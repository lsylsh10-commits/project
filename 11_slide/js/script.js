/* ==========================================
    집반찬연구소 이미지 슬라이드

    다른 Swiper 슬라이드와 충돌하지 않도록
    kidsSlide 전용 클래스와 변수 사용
========================================== */

const kidsSlide = new Swiper(".kids-slide", {

    /* -----------------------------------------
        슬라이드 방향
        horizontal = 좌우 방향
    ----------------------------------------- */
    direction: "horizontal",


    /* -----------------------------------------
        마지막 슬라이드 뒤에
        첫 번째 슬라이드가 다시 나오도록 설정
    ----------------------------------------- */
    loop: true,


    /* -----------------------------------------
        슬라이드가 넘어가는 속도
        700 = 0.7초
    ----------------------------------------- */
    speed: 700,


    /* -----------------------------------------
        자동 슬라이드

        웹페이지 로딩 후 자동 실행
        3초마다 다음 슬라이드로 이동
    ----------------------------------------- */
    autoplay: {

        /* 3초 */
        delay: 3000,

        /*
            사용자가 버튼을 클릭한 후에도
            자동 슬라이드 계속 실행
        */
        disableOnInteraction: false

    },


    /* -----------------------------------------
        좌우 이전 / 다음 버튼
    ----------------------------------------- */
    navigation: {

        /* 다음 버튼 */
        nextEl: ".kids-slide-next",

        /* 이전 버튼 */
        prevEl: ".kids-slide-prev"

    },


    /* -----------------------------------------
        페이지 번호 설정

        1 | 6
        2 | 6
        3 | 6
        ...
    ----------------------------------------- */
    on: {


        /* -------------------------------------
            Swiper 처음 실행될 때
        ------------------------------------- */
        init: function(){

            /* 현재 페이지 번호 */
            const current =
                document.querySelector(".kids-current");


            /* 전체 페이지 번호 */
            const total =
                document.querySelector(".kids-total");


            /*
                loop를 사용하기 때문에
                activeIndex가 아니라 realIndex 사용
            */
            current.textContent =
                this.realIndex + 1;


            /*
                전체 슬라이드 개수 표시
            */
            total.textContent =
                document.querySelectorAll(
                    ".kids-slide .swiper-slide:not(.swiper-slide-duplicate)"
                ).length;

        },


        /* -------------------------------------
            슬라이드가 변경될 때 실행
        ------------------------------------- */
        slideChange: function(){

            /* 현재 페이지 번호 */
            const current =
                document.querySelector(".kids-current");


            /*
                현재 슬라이드 번호 표시

                realIndex는 0부터 시작하므로
                +1을 해서 화면에 표시
            */
            current.textContent =
                this.realIndex + 1;

        }

    }

});


/* ==========================================
    집반찬연구소 상품 배너 슬라이드

    기존 이미지 슬라이드와 충돌하지 않도록
    productSwiper라는 별도의 변수와
    product 전용 클래스명을 사용
========================================== */

const productSwiper = new Swiper(".product-swiper", {

    /* -----------------------------------------
        한 화면에 보여주는 상품 개수
    ----------------------------------------- */
    slidesPerView: 4,


    /* -----------------------------------------
        상품 사이 간격
    ----------------------------------------- */
    spaceBetween: 20,


    /* -----------------------------------------
        한 번 움직일 때 상품 1개씩 이동

        자동재생 : 1개씩
        버튼 클릭 : 1개씩
    ----------------------------------------- */
    slidesPerGroup: 1,


    /* -----------------------------------------
        무한 반복

        마지막 상품 다음에도
        같은 방향으로 첫 상품이 이어짐
    ----------------------------------------- */
    loop: true,


    /* -----------------------------------------
        슬라이드 이동 속도
        700 = 0.7초
    ----------------------------------------- */
    speed: 700,


    /* -----------------------------------------
        자동재생

        페이지 로딩 후 자동 실행
        3초마다 상품 1개씩 이동
    ----------------------------------------- */
    autoplay: {

        /* 3초 */
        delay: 3000,

        /*
            좌우 버튼을 클릭한 뒤에도
            자동재생 계속 실행
        */
        disableOnInteraction: false

    },


    /* -----------------------------------------
        좌우 버튼

        버튼을 한 번 클릭하면
        상품이 1개씩 이동
    ----------------------------------------- */
    navigation: {

        /* 다음 상품 */
        nextEl: ".product-slide-next",

        /* 이전 상품 */
        prevEl: ".product-slide-prev"

    }

});